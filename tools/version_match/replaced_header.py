"""Turn the IDA agents' replaced-*.json files into src/platform/builds/build_<ver>_replaced.h.

Entries with same_semantics true go in, plus the ones in ADAPTED (the mod carries build-specific code for them);
the rest are printed (their features stand aside on that build). For code, the bytes the mod checks are read from the
new exe itself (128 bytes at the new address): the agent vouched for the semantics, the exe gives the exact bytes, and
the C++ check compares as many of them as the research build's array is long.
Usage: python replaced_header.py <out dir> <version> <new exe> <header path>
"""
import glob
import json
import os
import sys

from pe_image import IDA_BASE, Image

CHECK_BYTES = 128

# Research addresses whose 1.005 code differs in meaning but which the mod handles with build-specific code.
ADAPTED = {
    0x14111A301: "load-action sequence: the 1.005 redirect reads the family through [r14] (output_load_action_code.h)",
    0x14111A377: "load-action store: 6-byte mov [rbp+0E0h],al; the 1.005 store bytes and code are separate arrays",
}


def first_instruction(code: bytes, va: int) -> int:
    """Length of the first instruction if it is position-independent (no RIP-relative operand, no branch), else 0:
    what an entry redirect may copy into its trampoline (GameImage::EntryInstruction)."""
    import capstone
    from capstone import x86_const
    cs = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_64)
    cs.detail = True
    ins = next(cs.disasm(code[:16], va), None)
    if ins is None:
        return 0
    rip = any(op.type == x86_const.X86_OP_MEM and op.mem.base == x86_const.X86_REG_RIP for op in ins.operands)
    branch = ins.group(x86_const.X86_GRP_JUMP) or ins.group(x86_const.X86_GRP_CALL) or ins.group(x86_const.X86_GRP_RET)
    return 0 if rip or branch else ins.size


def main():
    out_dir, version, exe, header = sys.argv[1:5]
    img = Image(exe)
    entries, skipped = {}, []
    for path in sorted(glob.glob(os.path.join(out_dir, "replaced-*.json"))):
        data = json.load(open(path, encoding="utf-8"))
        items = data if isinstance(data, list) else (data.get("items") or data.get("facts") or [])
        for it in items:
            try:
                old = int(it["old"], 16)
                new = int(it["new"], 16)
            except (KeyError, ValueError, TypeError):
                skipped.append((os.path.basename(path), it.get("old"), "no usable old/new address"))
                continue
            note = " ".join(str(it.get("note", "")).split())
            if not it.get("same_semantics") and old not in ADAPTED:
                skipped.append((os.path.basename(path), it["old"], note[:120]))
                continue
            if old in ADAPTED:
                note = ADAPTED[old]
            code = img.section_of(new) == ".text"
            b = img.read(new, CHECK_BYTES) if code else b""
            if old in entries and entries[old][0] != new:
                skipped.append((os.path.basename(path), it["old"], f"conflicts with another file's 0x{entries[old][0]:X}"))
                continue
            entries[old] = (new, b, os.path.basename(path), str(it.get("confidence", "")), note)
    ns = "v" + version.replace(".", "_")
    lines = ["#pragma once", "",
             f"// Game version {version}: the addresses the offline matcher could not place, re-found by hand in IDA. For code,",
             f"// the {CHECK_BYTES} bytes at the new address as the exe holds them; a byte check there compares as many as the",
             "// research build's array is long. Generated by tools/version_match/replaced_header.py from the IDA agents'",
             "// replaced-*.json (Documentation/research/RE-1005-*.md). Sorted by the research build's RVA. An address missing",
             "// here and from the generated table stands its feature aside.", "",
             '#include "platform/build_translation.h"', "", "#include <array>", "#include <cstdint>", "",
             f"namespace lss::platform::builds::{ns} {{", ""]
    rows = []
    for old in sorted(entries):
        new, b, src, conf, note = entries[old]
        name = f"kBytes_{old - IDA_BASE:08X}"
        comment = f"// 0x{old:X} -> 0x{new:X} ({src}{', ' + conf if conf else ''}): {note[:100]}"
        if b:
            lines.append(comment)
            lines.append(f"inline constexpr std::uint8_t {name}[] = {{")
            for i in range(0, len(b), 16):
                lines.append("    " + ", ".join(f"0x{x:02X}" for x in b[i:i + 16]) + ",")
            lines.append("};")
            rows.append(f"    {{0x{old - IDA_BASE:08X}, 0x{new - IDA_BASE:08X}, {name}, {first_instruction(b, new)}}},")
        else:
            rows.append(f"    {{0x{old - IDA_BASE:08X}, 0x{new - IDA_BASE:08X}, {{}}}},  {comment}")
    lines += ["", f"inline constexpr std::array<ReplacedAddress, {len(rows)}> kReplaced{{{{", *rows, "}};", "",
              f"}}  // namespace lss::platform::builds::{ns}", ""]
    with open(header, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"{len(rows)} replaced addresses written; {len(skipped)} left out:")
    for s in skipped:
        print("  ", s)


if __name__ == "__main__":
    main()
